// MARK: - Client Options

/// Configuration options for SiloClient.
public struct SiloClientOptions: Sendable {
    /// Base URL of the Silo API (e.g. "https://api.silo.geekapps.io").
    public var baseUrl: String
    /// Optional URL for the Silo viewer app (used to build view URLs).
    public var appUrl: String?
    /// Bearer token for authentication.
    public var token: String?
    /// Default bucket slug used when no bucket is specified in upload calls.
    public var defaultBucket: String?

    public init(
        baseUrl: String,
        appUrl: String? = nil,
        token: String? = nil,
        defaultBucket: String? = nil
    ) {
        self.baseUrl = baseUrl
        self.appUrl = appUrl
        self.token = token
        self.defaultBucket = defaultBucket
    }
}

