/// Options for video uploads.
public struct VideoUploadOptions: Codable, Sendable {
    /// Generate video thumbnails.
    public var thumbnails: Bool?
    /// Generate a storyboard preview strip.
    public var storyboard: Bool?
    /// Auto-generate captions via speech recognition.
    public var autoCaptions: Bool?
    /// Languages for caption generation (e.g. ["en", "pt"]).
    public var languages: [String]?
    /// Target video codec (e.g. "h264", "h265", "av1").
    public var codec: String?
    /// Transcoding profile: pass specific profile names or "auto".
    public var transcoding: [String]?
    /// Run AI enrichment on the video.
    public var enrich: Bool?
    /// Target audio codec (e.g. "aac", "opus").
    public var audioCodec: String?
    /// Audio channel layout (e.g. "stereo", "5.1").
    public var audioChannels: String?
    /// Preserve Dolby Atmos audio.
    public var preserveAtmos: Bool?
    /// HDR handling ("preserve", "convert", "strip").
    public var hdr: String?
    /// Upload as a raw (unprocessed) video.
    public var raw: Bool?

    public init(
        thumbnails: Bool? = nil, storyboard: Bool? = nil,
        autoCaptions: Bool? = nil, languages: [String]? = nil,
        codec: String? = nil, transcoding: [String]? = nil,
        enrich: Bool? = nil, audioCodec: String? = nil,
        audioChannels: String? = nil, preserveAtmos: Bool? = nil,
        hdr: String? = nil, raw: Bool? = nil
    ) {
        self.thumbnails = thumbnails; self.storyboard = storyboard
        self.autoCaptions = autoCaptions; self.languages = languages
        self.codec = codec; self.transcoding = transcoding
        self.enrich = enrich; self.audioCodec = audioCodec
        self.audioChannels = audioChannels; self.preserveAtmos = preserveAtmos
        self.hdr = hdr; self.raw = raw
    }
}

