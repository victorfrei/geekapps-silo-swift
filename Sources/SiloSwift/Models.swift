/// A completed multipart part descriptor (sent to complete the upload).
public struct MultipartPart: Codable, Sendable {
    /// Part number (1-based).
    public let partNumber: Int
    /// ETag returned by S3 after the part upload.
    public let eTag: String

    public init(partNumber: Int, eTag: String) {
        self.partNumber = partNumber; self.eTag = eTag
    }

    private enum CodingKeys: String, CodingKey {
        case partNumber = "PartNumber"
        case eTag = "ETag"
    }
}

